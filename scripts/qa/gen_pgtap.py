"""Generate tests/db/schema.sql (pgTAP) from the SQLAlchemy models, so the database tests cannot drift.

    python scripts/qa/gen_pgtap.py            # rewrite tests/db/schema.sql
    scripts/qa/run_pgtap.sh <database_url>    # build the schema on PostgreSQL and run it (needs the pgtap extension)
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from sqlalchemy import CheckConstraint, ForeignKeyConstraint, UniqueConstraint  # noqa: E402

from app import models  # noqa: E402,F401
from app.database import Base  # noqa: E402

q = lambda s: "'" + str(s).replace("'", "''") + "'"  # noqa: E731
tests: list[str] = []
add = tests.append

for t in sorted(Base.metadata.sorted_tables, key=lambda t: t.name):
    add(f"SELECT has_table({q(t.name)});")
    pk = [c.name for c in t.primary_key.columns]
    add(f"SELECT col_is_pk({q(t.name)}, ARRAY[{', '.join(map(q, pk))}]);")
    for c in t.columns:
        add(f"SELECT has_column({q(t.name)}, {q(c.name)});")
        if not c.nullable and not c.primary_key:
            add(f"SELECT col_not_null({q(t.name)}, {q(c.name)});")
    for con in t.constraints:
        if isinstance(con, ForeignKeyConstraint):
            cols = [c.name for c in con.columns]
            ref = con.elements[0].column
            add(f"SELECT fk_ok({q(t.name)}, ARRAY[{', '.join(map(q, cols))}], {q(ref.table.name)}, ARRAY[{', '.join(q(e.column.name) for e in con.elements)}]);")
        elif isinstance(con, UniqueConstraint):
            add(f"SELECT col_is_unique({q(t.name)}, ARRAY[{', '.join(q(c.name) for c in con.columns)}]);")
        elif isinstance(con, CheckConstraint) and con.name:
            add(f"SELECT is((SELECT count(*)::int FROM pg_constraint WHERE conrelid = {q(t.name)}::regclass AND contype = 'c' AND conname = {q(con.name)}), 1, {q('check ' + con.name)});")
    for ix in t.indexes:
        add(f"SELECT has_index({q(t.name)}, {q(ix.name)});")

# billing_events is a platform-level idempotency and audit log: org_id is nullable (events for unknown
# transactions) and has no foreign key, so the record outlives an organization on purpose.
PLATFORM_TABLES = {"organizations", "billing_events"}
org_tables = sorted(t.name for t in Base.metadata.sorted_tables if "org_id" in t.columns and t.name not in PLATFORM_TABLES)
for name in org_tables:
    add(f"SELECT col_not_null({q(name)}, 'org_id', {q('tenant column is NOT NULL: ' + name)});")
if org_tables:
    add("SELECT is((SELECT count(*)::int FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey) "
        "WHERE c.contype = 'f' AND a.attname = 'org_id' AND c.confdeltype <> 'c'), 0, 'every org_id foreign key cascades on organization delete');")
# Only where the edition defines the DB-level index (BHE); BH lowercases e-mail in its validator instead.
if "users" in Base.metadata.tables and "lower(email)" in (Path(__file__).resolve().parents[2] / "app" / "database.py").read_text(encoding="utf-8").lower():
    add("SELECT is((SELECT count(*)::int FROM pg_indexes WHERE tablename = 'users' AND indexdef ILIKE '%UNIQUE%' AND indexdef ILIKE '%lower(%email%'), 1, 'user e-mail is unique case-insensitively');")

out = ["-- Generated by scripts/qa/gen_pgtap.py from app.models. Do not edit by hand.", "BEGIN;", f"SELECT plan({len(tests)});", *tests, "SELECT * FROM finish();", "ROLLBACK;", ""]
dest = Path(__file__).resolve().parents[2] / "tests" / "db" / "schema.sql"
dest.write_text("\n".join(out), encoding="utf-8")
print(f"{dest}: {len(tests)} assertions")
